/**
 * Archetype codegen — emits `src/archetypes/<name>/vars/{archetype,theme,balance}.ts`
 * from an ArchetypeManifest's § 5 TS schema.
 *
 * Contract per plan OL-546: dry-run → validate → overwrite. Each emit is
 * typechecked against the archetype's existing types.ts via an in-memory
 * ts-morph project before any disk write happens.
 */
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { Project } from 'ts-morph';
import type { ArchetypeManifest, VarsField, VarsInterface } from './parser';
import { STARTER_ROOT } from './parser';

export interface EmittedVars {
  archetypeTs: string;
  themeTs: string;
  balanceTs: string;
  indexTs: string;
}

export interface EmitOptions {
  /** Archetype directory root, e.g. `src/archetypes/producer`. Used for typecheck. */
  archetypeDir: string;
}

type InterfaceKind = 'archetype' | 'theme' | 'balance';

const FILE_HEADER = `/**
 * AUTO-GENERATED by scripts/archetype-tooling/codegen.ts from § 5 of
 * the paired archetype doc. Edit the doc, re-run \`pnpm codegen:archetype-vars <name>\`.
 * Direct edits to this file will be overwritten.
 */`;

// ─── Default-value rendering ──────────────────────────────────────────────

/**
 * Render the default expression for a field. Returns a string safe to drop
 * into `{ key: <expr> }` position. When no default can be synthesized,
 * returns a TODO-tagged placeholder and records the field in `todos`.
 */
function renderDefault(field: VarsField, todos: string[]): string {
  if (field.defaultExpr !== null) {
    return field.defaultExpr;
  }
  if (field.optional) {
    return 'undefined';
  }
  todos.push(field.name);
  const t = field.typeText.trim();

  if (/^number(\s*\|\s*null)?$/.test(t)) return '0';
  if (/^boolean(\s*\|\s*null)?$/.test(t)) return 'false';
  if (/^string(\s*\|\s*null)?$/.test(t)) return "''";
  if (/^DecimalSource(\s*\|\s*null)?$/.test(t)) return "'0'";

  // Union of single numeric literals (e.g. `0 | 1`, `4`): pick the first.
  if (/^(?:-?\d+(?:\.\d+)?)(\s*\|\s*-?\d+(?:\.\d+)?)*$/.test(t)) {
    return t.match(/-?\d+(?:\.\d+)?/)![0];
  }
  // Union of string literals — pick the first.
  if (/^'[^']+'(\s*\|\s*'[^']+')*$/.test(t)) {
    return t.match(/'[^']+'/)![0];
  }

  // Scalar arrays — empty array passes typecheck.
  if (/^(number|string|boolean|DecimalSource)\[\]$/.test(t)) return '[]';
  if (/^Array<(number|string|boolean|DecimalSource)>$/.test(t)) return '[]';

  // Anything structural (object literal, Record, Array-of-object, nested union):
  // emit an `unknown` cast so the assignment typechecks but clearly needs filling in.
  // Strip inline comments embedded in the type text before flattening — ts-morph
  // returns them verbatim, and they break TS when collapsed to one line.
  const flattened = t
    .replace(/\/\/[^\n]*/g, '') // drop line comments
    .replace(/\/\*[\s\S]*?\*\//g, '') // drop block comments
    .replace(/\s+/g, ' ')
    .trim();
  return `undefined as unknown as ${flattened}`;
}

function renderObjectLiteral(iface: VarsInterface, todos: string[]): string {
  const lines: string[] = [];
  for (const field of iface.fields) {
    const doc = renderFieldLeadingComment(field);
    if (doc) lines.push(`  ${doc}`);
    const defaultExpr = renderDefault(field, todos);
    lines.push(`  ${field.name}: ${defaultExpr},`);
  }
  return `{\n${lines.join('\n')}\n}`;
}

function renderFieldLeadingComment(field: VarsField): string | null {
  // Preserve a short trailing comment (post-default-strip) as a line hint;
  // leading JSDoc is too much to carry forward to the defaults file.
  if (field.trailingComment && field.trailingComment.length > 0) {
    return `// ${field.trailingComment}`;
  }
  return null;
}

// ─── Per-interface file emission ──────────────────────────────────────────

const KIND_TO_NAME_SUFFIX: Record<InterfaceKind, string> = {
  archetype: 'ArchetypeVars',
  theme: 'ThemeVars',
  balance: 'BalanceVars',
};

function pascalToScreaming(name: string): string {
  return name.replace(/([A-Z])/g, (_, c, i) => (i === 0 ? c : `_${c}`)).toUpperCase();
}

function emitInterfaceFile(
  kind: InterfaceKind,
  iface: VarsInterface,
  archetypeBaseName: string,
): { source: string; todos: string[] } {
  const todos: string[] = [];
  const typeName = iface.name;
  const constName = `DEFAULT_${archetypeBaseName.toUpperCase()}_${kind.toUpperCase()}_VARS`;
  void pascalToScreaming;

  const body = renderObjectLiteral(iface, todos);

  // Add `DecimalSource` only when the emitted body references it (via an
  // `unknown as X` cast for a TODO-structural field that embeds DecimalSource).
  // Checking the rendered body beats re-deriving from field metadata.
  const imports = [`import type { ${typeName} } from '../types';`];
  if (/\bDecimalSource\b/.test(body)) {
    imports.push(`import type { DecimalSource } from 'open-loop-engine';`);
  }

  const todoBanner =
    todos.length > 0
      ? `\n// TODO(codegen): ${todos.length} field${todos.length === 1 ? '' : 's'} without an inline default in § 5 — ${todos.join(', ')}.\n`
      : '\n';

  const source = `${FILE_HEADER}
${imports.join('\n')}
${todoBanner}
export const ${constName}: ${typeName} = ${body};
`;

  void KIND_TO_NAME_SUFFIX;
  return { source, todos };
}

function emitBarrelFile(screamingBase: string): string {
  return `${FILE_HEADER}
export { DEFAULT_${screamingBase}_ARCHETYPE_VARS } from './archetype';
export { DEFAULT_${screamingBase}_THEME_VARS } from './theme';
export { DEFAULT_${screamingBase}_BALANCE_VARS } from './balance';

import { DEFAULT_${screamingBase}_ARCHETYPE_VARS } from './archetype';
import { DEFAULT_${screamingBase}_THEME_VARS } from './theme';
import { DEFAULT_${screamingBase}_BALANCE_VARS } from './balance';

export const DEFAULT_${screamingBase}_VARS = {
  archetype: DEFAULT_${screamingBase}_ARCHETYPE_VARS,
  theme: DEFAULT_${screamingBase}_THEME_VARS,
  balance: DEFAULT_${screamingBase}_BALANCE_VARS,
};
`;
}

// ─── Entrypoint ──────────────────────────────────────────────────────────

export interface CodegenResult {
  emitted: EmittedVars;
  /** Fields without an inline `// default X` comment in § 5, by interface. */
  todos: {
    archetype: string[];
    theme: string[];
    balance: string[];
  };
  /** ts-morph typecheck diagnostics against the archetype's types.ts. Empty = green. */
  diagnostics: string[];
}

export function generateArchetypeVars(
  manifest: ArchetypeManifest,
  options: EmitOptions,
): CodegenResult {
  const vars = manifest.varsSchema;
  if (!vars || !vars.archetype || !vars.theme || !vars.balance) {
    throw new Error(
      `§ 5 of ${manifest.name}.md is missing one or more required interfaces (Archetype/Theme/Balance).`,
    );
  }

  const baseName = manifest.name.replace(/-./g, (m) => m[1].toUpperCase()); // kebab → camel
  // For the SCREAMING_CASE const, we want archetype name in upper flat form.
  // producer → PRODUCER, phase-shifter → PHASE_SHIFTER.
  const screamingBase = manifest.name.replace(/-/g, '_').toUpperCase();

  const archetype = emitInterfaceFile('archetype', vars.archetype, screamingBase);
  const theme = emitInterfaceFile('theme', vars.theme, screamingBase);
  const balance = emitInterfaceFile('balance', vars.balance, screamingBase);

  const emitted: EmittedVars = {
    archetypeTs: archetype.source,
    themeTs: theme.source,
    balanceTs: balance.source,
    indexTs: emitBarrelFile(screamingBase),
  };

  const diagnostics = typecheckAgainstTypesDts(emitted, options.archetypeDir);

  void baseName;
  return {
    emitted,
    todos: {
      archetype: archetype.todos,
      theme: theme.todos,
      balance: balance.todos,
    },
    diagnostics,
  };
}

/**
 * Load the archetype's existing types.ts into an in-memory ts-morph project
 * alongside the three emitted files, then collect diagnostics. Catches the
 * common break: renamed interface, added required field without default.
 */
function typecheckAgainstTypesDts(emitted: EmittedVars, archetypeDir: string): string[] {
  const typesPath = resolve(archetypeDir, 'types.ts');
  if (!existsSync(typesPath)) {
    return [`types.ts missing at ${typesPath} — cannot typecheck emitted vars`];
  }
  const typesSource = readFileSync(typesPath, 'utf8');

  // Map engine package imports to a stub to avoid disk traversal. The
  // only thing types.ts pulls from open-loop-engine is DecimalSource.
  const engineStub = `
export type DecimalSource = string | number;
`;

  const project = new Project({
    useInMemoryFileSystem: true,
    compilerOptions: {
      noEmit: true,
      strict: true,
      moduleResolution: 100,
      target: 99,
      module: 99,
      paths: { 'open-loop-engine': ['/engine-stub.ts'] },
    },
  });
  project.createSourceFile('/engine-stub.ts', engineStub);
  project.createSourceFile('/types.ts', typesSource);
  project.createSourceFile('/vars/archetype.ts', emitted.archetypeTs);
  project.createSourceFile('/vars/theme.ts', emitted.themeTs);
  project.createSourceFile('/vars/balance.ts', emitted.balanceTs);
  project.createSourceFile('/vars/index.ts', emitted.indexTs);

  const diagnostics = project.getPreEmitDiagnostics();
  return diagnostics.map((d) => {
    const file = d.getSourceFile()?.getFilePath() ?? '?';
    const line = d.getLineNumber() ?? 0;
    const msg = d.getMessageText();
    const msgStr = typeof msg === 'string' ? msg : JSON.stringify(msg);
    return `${file}:${line} — ${msgStr}`;
  });
}

// ─── Paths ───────────────────────────────────────────────────────────────

export function archetypeDirForName(name: string): string {
  return resolve(STARTER_ROOT, 'src/archetypes', name);
}
